export function buildUnitQuiz(unitIndex: number, introductoryQuestion: QuizQuestion): QuizQuestion[] {
  const questions = additionalQuestions[unitIndex];
  if (!questions || questions.length !== QUESTIONS_PER_LEVEL - 1) {
    throw new Error(`Unit ${unitIndex + 1} must have ${QUESTIONS_PER_LEVEL} questions`);
  }
  return [introductoryQuestion, ...questions.map(([question, answer, ...distractors]) => ({
    question,
    options: [answer, ...distractors],
    correctIndex: 0,
  }))];
}
